// ---------------------------------------------------------------------------
// Render MOVE_TABLES (the move prior's learned tables) as the source of
// src/moveTables.js. Shared by fit-move-prior.mjs --write and anything else that
// regenerates the file, so it has one layout.
// ---------------------------------------------------------------------------

const TYPES = ['pawn', 'knight', 'bishop', 'rook', 'queen', 'king'];
const num = x => (Math.abs(x) < 0.05 ? '0' : x.toFixed(1));

export function renderTables({ pst, capture, promo }, provenance) {
  const board = (row) => {
    // Printed rank 8 first, as a board is read from the mover's side.
    const lines = [];
    for (let r = 7; r >= 0; r--) {
      lines.push('      ' + Array.from({ length: 8 }, (_, f) => num(row[r * 8 + f]).padStart(7)).join(',') + ',');
    }
    return lines.join('\n');
  };
  return `// ---------------------------------------------------------------------------
// GENERATED by scripts/fit-move-prior.mjs --write. Do not edit by hand.
//
// The move prior's tables (see movePrior.js): a value per piece type and square,
// per captured piece type and per promotion type, in logits × 100. Squares are
// from the MOVER's side: each table is printed with the mover's back rank at the
// bottom, files a–h left to right.
//
// ${provenance}
// ---------------------------------------------------------------------------

export const MOVE_TABLES = {
  pst: {
${TYPES.map(t => `    ${t}: [\n${board(pst[t])}\n    ],`).join('\n')}
  },
  capture: { ${TYPES.map(t => `${t}: ${num(capture[t])}`).join(', ')} },
  promo: { ${['knight', 'bishop', 'rook', 'queen'].map(t => `${t}: ${num(promo[t])}`).join(', ')} },
};
`;
}
